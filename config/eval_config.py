"""Default settings for the RAGAS evaluation module.

These values are used when the corresponding CLI flags are not provided.
Edit them to match your preferred defaults.
"""

import os

# ---------------------------------------------------------------------------
# Result storage
# ---------------------------------------------------------------------------
# Directory where evaluation result JSON files are saved.
# Relative paths are resolved from the repository root.
eval_results_dir = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "eval_results",
)

# ---------------------------------------------------------------------------
# RAGAS metrics
# ---------------------------------------------------------------------------
# Metrics computed during evaluation.  Each name must match a metric
# importable from ``ragas.metrics``.
#
# Common choices:
#   "faithfulness"       -- is the answer grounded in the retrieved context?
#   "answer_relevancy"   -- does the answer address the question?
#   "context_precision"  -- are the top-ranked retrieved docs the most useful?
#   "context_recall"     -- was all required info retrieved?
default_metrics = [
    "faithfulness",
    "answer_relevancy",
    "context_precision",
    "context_recall",
]

# ---------------------------------------------------------------------------
# LLM judge
# ---------------------------------------------------------------------------
# By default the evaluation reuses whatever LLM backend is configured in
# ``llm_config.py`` (Ollama or OpenAI-compatible API) as the RAGAS judge.
#
# Set ``judge_model`` to a *different* model name if you want to use a
# separate (e.g. larger) model just for evaluation scoring.  ``None`` means
# "use the same model as llm_config".
judge_model = None

# ---------------------------------------------------------------------------
# Synthetic test-set generation
# ---------------------------------------------------------------------------
# Default number of questions generated by ``generate-testset``.
default_testset_size = 20
